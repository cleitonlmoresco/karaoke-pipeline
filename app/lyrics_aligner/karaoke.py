def _advance_width(text: str, font_size: int, font_name: str = "") -> float:
    if "times new roman" in font_name.lower():
        total = sum(_TIMES_BOLD_ADVANCE.get(ch, 0.5) for ch in text)
    else:
        total = len(text) * _CHAR_WIDTH_FACTOR
    return total * font_size


def _fit_verse_size(
    text: str, font_size: int, max_width: int, font_name: str = ""
) -> int:
    """Shrink one verse just enough to fit ``max_width`` at ``font_size``."""
    if max_width <= 0 or font_size <= 0:
        return font_size
    width = _advance_width(text, font_size, font_name)
    if width <= max_width:
        return font_size
    fitted = int(font_size * max_width / width)
    return max(28, min(font_size, fitted))


def _page_height(
    page: Sequence[Cue],
    style: KaraokeStyle,
    font_size: int | None = None,
) -> float:
    size = style.font_size if font_size is None else font_size
    return len(page) * size * 1.18


def _available_text_height(style: KaraokeStyle, play_res_y: int) -> int:
    return max(1, int(play_res_y) - 2 * int(style.margin_v))


def _min_font_size(play_res_y: int) -> int:
    """Minimum font size scaled with the output height (44 px at 1080p)."""
    return max(1, int(round(_MIN_AUTO_FONT_SIZE * int(play_res_y) / 1080)))


def _fit_font_size(
    line_count: int,
    longest_chars: int,
    style: KaraokeStyle,
    play_res_x: int,
    play_res_y: int,
) -> int:
    """Largest size that fits the page height and the longest verse width."""
    if line_count <= 0:
        return style.font_size
    height = _available_text_height(style, play_res_y)
    height_size = int(height / (line_count * _LINE_HEIGHT_FACTOR))
    width = max(1, int(play_res_x) - style.margin_l - style.margin_r)
    width_size = (
        int(width / (longest_chars * _CHAR_WIDTH_FACTOR))
        if longest_chars > 0
        else style.font_size
    )
    return max(
        _min_font_size(play_res_y),
        min(style.font_size, height_size, width_size),
    )


def _longest_cue_chars(page: Sequence[Cue]) -> int:
    return max((len(cue.text.strip()) for cue in page), default=0)


def _max_lines_at_min_font(style: KaraokeStyle, play_res_y: int) -> int:
    height = _available_text_height(style, play_res_y)
    return max(
        1,
        int(height / (_min_font_size(play_res_y) * _LINE_HEIGHT_FACTOR)),
    )


def stanza_boundaries_from_lyrics(
    lyrics_text: str,
    cues: Sequence[Cue],
    *,
    max_chars: int = 80,
) -> frozenset[int]:
    """Map blank lines in the source lyrics to cue indexes.

    Used by the "por estrofes" interpretation mode: each stanza forced by a
    blank line starts a new slide, while verses closer than ``max_gap`` (6 s)
    stay together inside the same stanza.
    """
    if not cues:
        return frozenset()

    source_lines: list[str] = []
    starts: set[int] = set()
    pending_blank = False
    for raw_line in lyrics_text.splitlines():
        line = normalize_line(raw_line)
        if not line:
            pending_blank = True
            continue
        parts = split_lyrics(line, max_chars=max_chars)
        if not parts:
            continue
        if pending_blank and source_lines:
            starts.add(len(source_lines))
        pending_blank = False
        source_lines.extend(parts)
    if not source_lines:
        return frozenset()

    def fold(text: str) -> str:
        return "".join(
            char for char in unicodedata.normalize("NFKC", text).casefold()
            if not char.isspace()
        )

    boundaries: set[int] = set()
    cue_index = 0
    for line_index, line_text in enumerate(source_lines):
        if line_index in starts and cue_index < len(cues):
            boundaries.add(cue_index)
        target = fold(line_text)
        collected = ""
        while cue_index < len(cues):
            collected += cues[cue_index].text
            cue_index += 1
            if fold(collected) == target:
                break
            if len(fold(collected)) > len(target) + 5:
                break
    return frozenset(boundaries)


def _paginate_cues_adaptive(
    cues: Sequence[Cue],
    lines_per_slide: int,
    *,
    style: KaraokeStyle,
    play_res_x: int,
    play_res_y: int,
    max_gap: float = 6.0,
) -> tuple[list[list[Cue]], list[int]]:
    """Group each sung phrase on one slide, shrinking the font when needed.

    A phrase is the run of cues between pauses longer than ``max_gap``.
    Lines inside a fast phrase stay together even when they exceed
    ``lines_per_slide``; the font is reduced just enough to fit the whole
    phrase and the longest verse. Phrases too long for the minimum font are
    split into balanced pages that share the same font size.
    """
    if lines_per_slide <= 0:
        return ([list(cues)] if cues else []), [style.font_size]

    blocks: list[list[Cue]] = []
    current: list[Cue] = []
    boundaries = style.stanza_boundaries or frozenset()
    for index, cue in enumerate(cues):
        if current:
            gap = cue.start - current[-1].end
            last_duration = current[-1].end - current[-1].start
            long_break = (
                last_duration >= _LONG_CUE_SPLIT_SECONDS
                and gap >= _LONG_CUE_MIN_GAP
            )
            if index in boundaries or gap > max_gap or long_break:
                blocks.append(current)
                current = []
        current.append(cue)
    if current:
        blocks.append(current)

    max_lines = _max_lines_at_min_font(style, play_res_y)
    pages: list[list[Cue]] = []
    sizes: list[int] = []
    for block in blocks:
        longest = _longest_cue_chars(block)
        if len(block) <= max_lines:
            pages.append(block)
            sizes.append(
                _fit_font_size(
                    len(block),
                    longest,
                    style,
                    play_res_x,
                    play_res_y,
                )
            )
            continue
        page_count = math.ceil(len(block) / max_lines)
        base, extra = divmod(len(block), page_count)
        chunk_lengths = [base + 1] * extra + [base] * (page_count - extra)
        largest = max(chunk_lengths)
        block_size = _fit_font_size(
            largest,
            longest,
            style,
            play_res_x,
            play_res_y,
        )
        offset = 0
        for length in chunk_lengths:
            pages.append(block[offset : offset + length])
            sizes.append(block_size)
            offset += length
    return pages, sizes


def _pause_crossed(
    cues: Sequence[Cue], first: int, last: int, max_gap: float = 2.0
) -> bool:
    """True when any gap between ``first`` and ``last`` exceeds ``max_gap``."""
    return any(
        cues[index + 1].start - cues[index].end > max_gap
        for index in range(first, last)
    )


def _transition_tags(
    kind: str,
    *,
    x: int,
    y: int,
    shift: float,
    start_ms: int,
    duration_ms: int,
    entering: bool,
    both: bool = False,
) -> str:
    """Build the ASS override tags for one side of a page transition."""
    if kind == "none":
        return ""
    if kind == "fade":
        if both:
            return f"{{\\fad({duration_ms},{duration_ms})}}"
        if entering:
            return f"{{\\fad({duration_ms},0)}}"
        return f"{{\\fad(0,{duration_ms})}}"
    if kind in ("scroll", "up"):
        if both:
            return (
                f"{{\\move({x},{int(y + shift)},{x},{y},0,{duration_ms})"
                f"\\fad({duration_ms},{duration_ms})}}"
            )
        if entering:
            return (
                f"{{\\move({x},{int(y + shift)},{x},{y},0,{duration_ms})"
                f"\\fad({duration_ms},0)}}"
            )
        return (
            f"{{\\move({x},{y},{x},{int(y - shift)},{start_ms},{start_ms + duration_ms})"
            f"\\fad(0,{duration_ms})}}"
        )
    if both:
        return (
            f"{{\\move({x},{int(y - shift)},{x},{y},0,{duration_ms})"
            f"\\fad({duration_ms},{duration_ms})}}"
        )
    if entering:
        return (
            f"{{\\move({x},{int(y - shift)},{x},{y},0,{duration_ms})"
            f"\\fad({duration_ms},0)}}"
        )
    return (
        f"{{\\move({x},{y},{x},{int(y + shift)},{start_ms},{start_ms + duration_ms})"
        f"\\fad(0,{duration_ms})}}"
    )


def _render_page_event(
    page: Sequence[Cue],
    *,
    style: KaraokeStyle,
    units: Sequence[AlignmentUnit] | Sequence[Mapping[str, Any]],
    offset_seconds: float,
    end_seconds: float,
    tags: str = "",
    event_start: float | None = None,
) -> str:
    """Render one page of lyrics with progressive word timing across all lines."""
    page_start = page[0].start
    start_seconds = page_start if event_start is None else event_start
    parts: list[str] = [_inline_color(style.active_color, style.normal_color)]
    cursor = start_seconds
    for index, cue in enumerate(page):
        if index > 0:
            gap = cue.start - cursor
            if gap > 0.005:
                parts.append("{" + _k_tag(style, _cs(gap)) + "}")
            parts.append("\\N")
            cursor = max(cursor, cue.start)
        words = word_timings(cue.text, cue.start, cue.end, units)
        if not words:
            parts.append(_escape_ass_text(cue.text))
            cursor = max(cursor, cue.end)
            continue
        for word in words:
            gap = word.start - cursor
            if gap > 0.005:
                parts.append("{" + _k_tag(style, _cs(gap)) + "}")
            parts.append("{" + _k_tag(style, _cs(word.end - word.start)) + "}" + _escape_ass_text(word.text) + " ")
            cursor = max(cursor, word.end)
        if cursor < cue.end - 0.005:
            parts.append("{" + _k_tag(style, _cs(cue.end - cursor)) + "}")
            cursor = cue.end
    text = "".join(parts).rstrip()
    return (
        "Dialogue: 0,"
        f"{format_ass_timestamp(start_seconds + offset_seconds)},"
        f"{format_ass_timestamp(end_seconds + offset_seconds)},"
        f"VilmKaraoke,,0,0,0,,{tags}{text}"
    )


def render_karaoke_ass(
    cues: Sequence[Cue],
    *,
    title: str = "Vilm Karaoke",
    offset_seconds: float = 0.0,
    style: KaraokeStyle | None = None,
    units: Sequence[AlignmentUnit] | Sequence[Mapping[str, Any]] = (),
    play_res_x: int = 1920,
    play_res_y: int = 1080,
) -> str:
    """Render progressive karaoke: the current line fills word by word."""
    style = style or KaraokeStyle()
    validate_karaoke_style(style)
    if play_res_x <= 0 or play_res_y <= 0:
        raise ValueError("A resolução do ASS deve ser positiva.")
    title = " ".join(title.split()) or "Vilm Karaoke"
    font_name = normalize_font_cascade(style.font_name)

    header = _KARAOKE_HEADER.format(
        title=title,
        play_res_x=play_res_x,
        play_res_y=play_res_y,
        font_name=font_name,
        font_size=style.font_size,
        active_color=ass_color(style.active_color),
        normal_color=ass_color(style.normal_color),
        outline_color=ass_color(style.outline_color),
        back_color=ass_color(style.back_color),
        bold=-1 if style.bold else 0,
        outline=f"{style.outline:g}",
        shadow=f"{style.shadow:g}",
        alignment=style.alignment,
        margin_l=style.margin_l,
        margin_r=style.margin_r,
        margin_v=style.margin_v,
    )

    events: list[str] = []
    if style.lines_per_slide > 0:
        pages, page_font_sizes = _paginate_cues_adaptive(
            cues,
            style.lines_per_slide,
            style=style,
            play_res_x=play_res_x,
            play_res_y=play_res_y,
        )
        entry_lead_s = max(0.0, style.entry_lead_ms / 1000.0)
        event_starts: list[float] = []
        for index, page in enumerate(pages):
            lead = entry_lead_s
            if index > 0:
                lead = min(
                    lead,
                    max(0.0, page[0].start - pages[index - 1][-1].end - 0.01),
                )
            event_starts.append(max(0.0, page[0].start - lead))
        duration_ms = style.transition_ms
        duration_s = duration_ms / 1000.0
        anchor_x, anchor_y = _anchor_position(style, play_res_x, play_res_y)
        transitions: list[dict[str, float] | None] = [None] * max(0, len(pages) - 1)
        for index in range(len(pages) - 1):
            current, following = pages[index], pages[index + 1]
            gap = event_starts[index + 1] - current[-1].end
            if style.transition == "none" or gap > 2.0:
                continue
            if style.transition == "scroll":
                shift = min(
                    float(play_res_y),
                    anchor_y
                    + max(
                        _page_height(current, style, page_font_sizes[index]),
                        _page_height(following, style, page_font_sizes[index + 1]),
                    )
                    / 2
                    + max(
                        page_font_sizes[index],
                        page_font_sizes[index + 1],
                    )
                    * 1.2,
                )
            else:
                shift = max(
                    page_font_sizes[index],
                    page_font_sizes[index + 1],
                ) * 1.2
            transitions[index] = {"start": event_starts[index + 1], "shift": shift}
        for index, page in enumerate(pages):
            end_seconds = page[-1].end
            exit_info = transitions[index] if index < len(transitions) else None
            enter_info = transitions[index - 1] if index > 0 else None
            if index + 1 < len(pages):
                next_start = event_starts[index + 1]
                # Never show two pages at the same time: libass moves
                # overlapping events around to avoid collisions, which pushes
                # the lyrics down and clips them. Hold each page for up to one
                # second, but always stop just before the next page starts.
                if next_start > page[-1].end:
                    end_seconds = min(next_start - 0.01, end_seconds + 1.0)
                else:
                    end_seconds = max(page[0].start + 0.05, next_start - 0.01)
            tags = ""
            if style.transition == "fade":
                # Fade only in the silence after the last word of the page:
                # dimming the text while it is still being sung cuts the end
                # of fast lines. The next page is shown at full opacity from
                # its first word, because a fade-in would hide its beginning.
                available_ms = max(
                    0, int(round((end_seconds - page[-1].end) * 1000))
                )
                fade_out_ms = min(duration_ms, available_ms)
                if exit_info is not None and fade_out_ms >= 60:
                    tags = f"{{\\fad(0,{fade_out_ms})}}"
            else:
                if exit_info is not None:
                    # Finish the exit animation before the next page starts instead
                    # of extending this event into the next page.
                    exit_start = min(exit_info["start"], end_seconds - duration_s)
                    start_ms = max(
                        0, int(round((exit_start - event_starts[index]) * 1000))
                    )
                if enter_info is not None and exit_info is not None:
                    # The page enters scrolling and leaves fading while the next
                    # page scrolls in; ASS can only animate position once per event.
                    tags = _transition_tags(
                        style.transition,
                        x=anchor_x,
                        y=anchor_y,
                        shift=enter_info["shift"],
                        start_ms=0,
                        duration_ms=duration_ms,
                        entering=True,
                        both=True,
                    )
                elif exit_info is not None:
                    tags = _transition_tags(
                        style.transition,
                        x=anchor_x,
                        y=anchor_y,
                        shift=exit_info["shift"],
                        start_ms=start_ms,
                        duration_ms=duration_ms,
                        entering=False,
                    )
                elif enter_info is not None:
                    tags = _transition_tags(
                        style.transition,
                        x=anchor_x,
                        y=anchor_y,
                        shift=enter_info["shift"],
                        start_ms=0,
                        duration_ms=duration_ms,
                        entering=True,
                    )
            page_font_size = page_font_sizes[index]
            if page_font_size != style.font_size:
                tags = f"{{\\fs{page_font_size}}}" + tags
            events.append(
                _render_page_event(
                    page,
                    style=style,
                    units=units,
                    offset_seconds=offset_seconds,
                    end_seconds=end_seconds,
                    tags=tags,
                    event_start=event_starts[index],
                )
            )
    else:
        # Rolling window: the current line is the first of the visible block
        # (``lines_before=0``) and the following lines give context. Missing
        # lines (edges or across a long pause) are invisible dots so every
        # event keeps the same visual height.
        anchor_x, anchor_y = _anchor_position(style, play_res_x, play_res_y)
        verse_width = max(1, play_res_x - style.margin_l - style.margin_r)
        invisible = "{\\alpha&HFF&\\fscx100\\fscy100}."
        lead_s = _SCROLL_ENTRY_LEAD_MS / 1000.0
        pause_gap = max(0.5, float(style.scroll_pause_seconds))
        active_size = int(style.active_font_size or style.font_size)
        base_size = int(style.font_size)
        grow_pct = 100.0 * active_size / base_size if base_size else 100.0
        shrink_pct = 100.0 * base_size / active_size if active_size else 100.0
        line_step = max(1, int(round(style.font_size * _LINE_HEIGHT_FACTOR)))
        event_starts: list[float] = []
        for index, cue in enumerate(cues):
            if index == 0:
                # The first slide has nothing above it: show it exactly at its
                # cue start instead of adding another entry lead.
                event_starts.append(max(0.0, cue.start))
                continue
            lead = lead_s
            lead = min(
                lead,
                max(0.0, cue.start - cues[index - 1].end - 0.01),
            )
            event_starts.append(max(0.0, cue.start - lead))
        for index, cue in enumerate(cues):
            move_ms = max(
                200,
                min(style.transition_ms, int(round((cue.end - cue.start) * 500))),
            )
            # Scroll at the end of the verse: the active line rises and fades
            # out exactly when its time ends, while the lines below rise into
            # their new positions.
            transition_start_ms = max(
                0, int(round((cue.end - event_starts[index]) * 1000)) - move_ms
            )
            transition_end_ms = transition_start_ms + move_ms
            # When the previous verse is still on screen, the new block starts
            # exactly where the old one ended and carries one extra line at the
            # top. That line fades out while the block rises one line, so the
            # shared lines stay put and nothing jumps.
            continuous = False
            if index > 0:
                continuous = cue.start - cues[index - 1].end <= pause_gap
            first_offset = -style.lines_before - (
                1 if continuous and style.lines_before > 0 else 0
            )
            segments: list[str] = []
            for offset in range(first_offset, style.lines_after + 1):
                other = index + offset
                crossed = False
                if other < 0 or other >= len(cues):
                    crossed = True
                elif offset < 0:
                    crossed = _pause_crossed(cues, other, index, pause_gap)
                elif offset > 0:
                    crossed = _pause_crossed(cues, index, other, pause_gap)
                if crossed:
                    segments.append(invisible)
                    continue
                other_cue = cues[other]
                if other == index:
                    words = word_timings(
                        other_cue.text, other_cue.start, other_cue.end, units
                    )
                    start_size = base_size if continuous else active_size
                    if continuous and active_size != base_size:
                        grow_scale = active_size / base_size
                    else:
                        grow_scale = 1.0
                    fit_size = _fit_verse_size(
                        other_cue.text + " ",
                        start_size,
                        int(verse_width / grow_scale),
                        style.font_name,
                    )
                    segment = f"{{\\fs{fit_size}\\fscx100\\fscy100}}"
                    if continuous and active_size != base_size:
                        segment += (
                            f"{{\\t(0,{move_ms},"
                            f"\\fscx{grow_pct:.1f}\\fscy{grow_pct:.1f})}}"
                        )
                    segment += _inline_color(
                        style.active_color, style.normal_color
                    )
                    segment += (
                        f"{{\\t({transition_start_ms},{transition_end_ms},"
                        f"\\alpha&HFF&)}}"
                    )
                    cursor = event_starts[index]
                    for word in words:
                        gap = word.start - cursor
                        if gap > 0.005:
                            segment += "{" + _k_tag(style, _cs(gap)) + "}"
                        segment += (
                            "{" + _k_tag(style, _cs(word.end - word.start)) + "}"
                            f"{_escape_ass_text(word.text)} "
                        )
                        cursor = max(cursor, word.end)
                    if cursor < cue.end - 0.005:
                        segment += "{" + _k_tag(style, _cs(cue.end - cursor)) + "}"
                    segments.append(segment)
                else:
                    size = base_size
                    extra_top = continuous and offset == first_offset
                    old_active = (
                        continuous
                        and style.lines_before > 0
                        and offset == -1
                    )
                    new_bottom = (
                        continuous
                        and offset == style.lines_after
                        and style.lines_after > 0
                    )
                    if extra_top:
                        # The line that was on top of the previous block.
                        size = (
                            active_size if style.lines_before == 0 else base_size
                        )
                    elif old_active:
                        # It was the active line; shrink it to context size.
                        size = active_size
                    fit_size = _fit_verse_size(
                        other_cue.text + " ", size, verse_width, style.font_name
                    )
                    segment = f"{{\\fs{fit_size}\\fscx100\\fscy100}}"
                    segment += _inline_color(
                        style.normal_color, style.normal_color
                    )
                    if extra_top:
                        segment += (
                            f"{{\\t({transition_start_ms},{transition_end_ms},"
                            f"\\alpha&HFF&)}}"
                        )
                    elif new_bottom:
                        segment += (
                            f"{{\\alpha&HFF&\\t({transition_start_ms},"
                            f"{transition_end_ms},\\alpha&H00&)}}"
                        )
                    elif old_active and active_size != base_size:
                        segment += (
                            f"{{\\t(0,{move_ms},"
                            f"\\fscx{shrink_pct:.1f}\\fscy{shrink_pct:.1f})}}"
                        )
                    segment += _escape_ass_text(other_cue.text)
                    segments.append(segment)
            text = "\\N".join(segments)

            end_seconds = cue.end + 1.0
            fade_ms = 0
            if index + 1 < len(cues):
                following = cues[index + 1]
                next_event_start = event_starts[index + 1]
                gap = following.start - cue.end
                if gap <= pause_gap:
                    # The next block starts at the same instant and shares the
                    # same lines, so the hand-off is invisible.
                    end_seconds = max(cue.start + 0.05, next_event_start)
                else:
                    # Long pause: keep the line fully visible for one second
                    # after the last word, then fade it out.
                    fade_ms = min(style.transition_ms, 400)
                    end_seconds = cue.end + 1.0 + fade_ms / 1000.0
            else:
                fade_ms = min(style.transition_ms, 400)
                end_seconds = cue.end + 1.0 + fade_ms / 1000.0
            if continuous:
                start_y = int(round(anchor_y + line_step / 2))
                end_y = int(round(anchor_y - line_step / 2))
            else:
                start_y = int(anchor_y + line_step)
                end_y = int(anchor_y)
            tags = (
                f"{{\\move({anchor_x},{start_y},"
                f"{anchor_x},{end_y},"
                f"{transition_start_ms},{transition_end_ms})"
            )
            if fade_ms:
                tags += f"\\fad(0,{fade_ms})"
            tags += "}"
            events.append(
                "Dialogue: 0,"
                f"{format_ass_timestamp(event_starts[index] + offset_seconds)},"
                f"{format_ass_timestamp(end_seconds + offset_seconds)},"
                f"VilmKaraoke,,0,0,0,,{tags}{text}"
            )
    return header + "\n".join(events) + ("\n" if events else "")


def _parse_hex_color(color: str) -> str:
    digits = color.strip().removeprefix("#")
    if len(digits) != 6:
        raise ValueError("A cor deve usar o formato #RRGGBB.")
    try:
        int(digits, 16)
    except ValueError as exc:
        raise ValueError("A cor deve usar o formato #RRGGBB.") from exc
    return digits


def build_background_command(
    ffmpeg: str | Path,
    audio_path: str | Path,
    output_path: str | Path,
    *,
    color: str = "#0B1D3A",
    image: str | Path | None = None,
    width: int = 1920,
    height: int = 1080,
    fps: int = 30,
    preset: str = "medium",
    crf: int = 18,
    fit: str = "contain",
    threads: int | None = None,
) -> list[str]:
    """FFmpeg command that turns audio into a video with a fixed background."""
    if width <= 0 or height <= 0 or fps <= 0:
        raise ValueError("Largura, altura e FPS devem ser positivos.")
    if fit not in ("contain", "cover"):
        raise ValueError("O ajuste da imagem deve ser 'contain' ou 'cover'.")
    command = [
        str(ffmpeg),
        "-hide_banner",
        "-nostdin",
        "-y",
        "-loglevel",
        "error",
    ]
    if image:
        image_path = Path(image)
        if not image_path.is_file():
            raise FileNotFoundError(image_path)
        # A imagem é estática: entra a 1 fps e o filtro fps=30 duplica os
        # quadros. Sem isso o PNG é decodificado 25x por segundo à toa.
        command += ["-loop", "1", "-framerate", "1", "-i", str(image_path)]
        if fit == "cover":
            # Alinha o corte pelo topo: fundos com logotipo no alto (ex.: arte
            # 3:2 usada em 16:9) mantem a marca e perdem apenas a base.
            scale_filter = (
                f"scale={width}:{height}:force_original_aspect_ratio=increase,"
                f"crop={width}:{height}:0:0,setsar=1,fps={fps}"
            )
        else:
            scale_filter = (
                f"scale={width}:{height}:force_original_aspect_ratio=decrease,"
                f"pad={width}:{height}:(ow-iw)/2:(oh-ih)/2"
                f":color=0x{_parse_hex_color(color)},setsar=1,fps={fps}"
            )
        command += ["-i", str(audio_path), "-vf", scale_filter]
    else:
        command += [
            "-f",
            "lavfi",
            "-i",
            f"color=c=0x{_parse_hex_color(color)}:s={width}x{height}:r={fps}",
            "-i",
            str(audio_path),
        ]
    command += [
        "-map",
        "0:v:0",
        "-map",
        "1:a:0",
        "-c:v",
        "libx264",
        "-preset",
        preset,
        "-crf",
        str(int(crf)),
        "-pix_fmt",
        "yuv420p",
    ]
    if threads is not None and threads > 0:
        command += ["-threads", str(int(threads))]
    command += [
        "-c:a",
        "aac",
        "-b:a",
        "192k",
        "-shortest",
        "-movflags",
        "+faststart",
        str(output_path),
    ]
    return command


def _probe_duration(ffmpeg_path: str | Path, media_path: str | Path) -> float | None:
    """Return the media duration in seconds using the bundled ffprobe."""
    import os

    ffmpeg_path = Path(ffmpeg_path)
    name = "ffprobe.exe" if os.name == "nt" else "ffprobe"
    ffprobe = ffmpeg_path.with_name(name)
    if not ffprobe.is_file():
        return None
    completed = subprocess.run(
        [
            str(ffprobe),
            "-v",
            "error",
            "-show_entries",
            "format=duration",
            "-of",
            "default=nw=1:nk=1",
            str(media_path),
        ],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    try:
        value = float(completed.stdout.strip())
    except ValueError:
        return None
    return value if value > 0 else None


def make_background_video(
    audio_path: str | Path,
    output_path: str | Path,
    *,
    color: str = "#0B1D3A",
    image: str | Path | None = None,
    width: int = 1920,
    height: int = 1080,
    fps: int = 30,
    ffmpeg: str | Path | None = None,
    preset: str = "medium",
    crf: int = 18,
    fit: str = "contain",
) -> Path:
    """Create a background video whose audio comes from the source file."""
    from .publish import find_ffmpeg

    audio_path = Path(audio_path).resolve()
    output_path = Path(output_path).resolve()
    if not audio_path.is_file():
        raise FileNotFoundError(audio_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    ffmpeg_path = find_ffmpeg(ffmpeg)
    command = build_background_command(
        ffmpeg_path,
        audio_path,
        output_path,
        color=color,
        image=image,
        width=width,
        height=height,
        fps=fps,
        preset=preset,
        crf=crf,
        fit=fit,
    )
    duration = _probe_duration(ffmpeg_path, audio_path)
    if duration and duration > 0:
        # Garante que o vídeo termine junto com o áudio, sem quadros extras.
        command[-1:-1] = ["-t", f"{duration:.3f}"]
    completed = subprocess.run(
        command,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    if completed.returncode != 0:
        detail = completed.stderr.strip() or completed.stdout.strip()
        if "memory" in detail.casefold() or "memória" in detail.casefold():
            # Segunda tentativa com menos memória: preset leve e 1 thread.
            retry_command = build_background_command(
                find_ffmpeg(ffmpeg),
                audio_path,
                output_path,
                color=color,
                image=image,
                width=width,
                height=height,
                fps=fps,
                preset="veryfast",
                crf=crf,
                fit=fit,
                threads=1,
            )
            retry = subprocess.run(
                retry_command,
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                check=False,
            )
            if retry.returncode == 0:
                completed = retry
            else:
                detail += " | nova tentativa: " + (
                    retry.stderr.strip() or retry.stdout.strip()
                )
        if completed.returncode != 0:
            raise RuntimeError(
                f"Falha ao criar o vídeo de fundo (código {completed.returncode}): {detail}"
            )
    if not output_path.is_file() or output_path.stat().st_size == 0:
        raise RuntimeError("O FFmpeg não criou o vídeo de fundo.")
    return output_path