def validate_karaoke_style(style: KaraokeStyle) -> None:
    if not style.font_name.strip():
        raise ValueError("O nome da fonte não pode ser vazio.")
    if not 8 <= style.font_size <= 300:
        raise ValueError("O tamanho da fonte deve ficar entre 8 e 300.")
    if not 1 <= style.alignment <= 9:
        raise ValueError("O alinhamento ASS deve ficar entre 1 e 9.")
    if min(style.margin_l, style.margin_r, style.margin_v) < 0:
        raise ValueError("As margens não podem ser negativas.")
    if min(style.outline, style.shadow) < 0:
        raise ValueError("Contorno e sombra não podem ser negativos.")
    if not 0 <= style.lines_before <= 5 or not 0 <= style.lines_after <= 5:
        raise ValueError("As linhas antes/depois devem ficar entre 0 e 5.")
    if not 0 <= style.lines_per_slide <= 5:
        raise ValueError("As linhas por tela devem ficar entre 0 e 5.")
    if style.transition not in {"none", "scroll", "fade", "up", "down"}:
        raise ValueError("A transição deve ser none, scroll, fade, up ou down.")
    if not 100 <= style.transition_ms <= 2000:
        raise ValueError("A duração da transição deve ficar entre 100 e 2000 ms.")
    if not 0 <= style.entry_lead_ms <= 2000:
        raise ValueError("A entrada dos slides deve ficar entre 0 e 2000 ms.")
    if style.active_font_size and not 8 <= style.active_font_size <= 300:
        raise ValueError("A fonte ativa deve ficar entre 8 e 300 px ou ser 0.")
    if not 0.5 <= style.scroll_pause_seconds <= 10:
        raise ValueError("A pausa da rolagem deve ficar entre 0,5 e 10 s.")
    ass_color(style.normal_color)
    ass_color(style.active_color)
    ass_color(style.outline_color)
    ass_color(style.back_color)


def _unit_tuples(
    units: Sequence[AlignmentUnit] | Sequence[Mapping[str, Any]],
) -> list[tuple[str, float, float]]:
    result: list[tuple[str, float, float]] = []
    for unit in units:
        if isinstance(unit, AlignmentUnit):
            text, start, end = unit.text, unit.start, unit.end
        else:
            text = str(unit.get("text", ""))
            start = float(unit.get("start") or 0.0)
            end_value = unit.get("end")
            end = float(end_value) if end_value is not None else start
        if text.strip() and end >= start:
            result.append((text, start, end))
    return result


def word_timings(
    cue_text: str,
    cue_start: float,
    cue_end: float,
    units: Sequence[AlignmentUnit] | Sequence[Mapping[str, Any]] = (),
) -> list[KaraokeWord]:
    """Word times from ASR units, with proportional fallback inside gaps."""
    words = cue_text.split()
    if not words:
        return []
    cue_start = float(cue_start)
    cue_end = max(float(cue_end), cue_start + 0.01)
    normalized = normalize_for_match(cue_text)

    word_spans: list[tuple[int, int]] = []
    cursor = 0
    for word in words:
        key = normalize_for_match(word)
        position = normalized.find(key, cursor)
        if position < 0:
            position = normalized.find(key)
        if position < 0:
            position = cursor
        word_spans.append((position, position + max(1, len(key))))
        cursor = position + len(key)

    unit_spans: list[tuple[int, int, float, float]] = []
    cursor = 0
    for text, start, end in _unit_tuples(units):
        key = normalize_for_match(text)
        if not key:
            continue
        # Only units around this cue: the same chorus appears many times, and
        # matching an earlier repetition would collapse the karaoke timing.
        if end < cue_start - 0.5 or start > cue_end + 0.5:
            continue
        position = normalized.find(key, cursor)
        if position < 0:
            position = normalized.find(
                key,
                max(0, cursor - 4),
                min(len(normalized), cursor + max(64, len(key) * 4)),
            )
        if position < 0:
            continue
        unit_spans.append((position, position + len(key), start, end))
        cursor = position + len(key)

    def overlap_time(span: tuple[int, int]) -> tuple[float, float] | None:
        span_start, span_end = span
        overlaps: list[tuple[float, float]] = []
        for unit_start, unit_end, time_start, time_end in unit_spans:
            overlap_start = max(span_start, unit_start)
            overlap_end = min(span_end, unit_end)
            if overlap_start >= overlap_end or unit_end <= unit_start:
                continue
            width = unit_end - unit_start
            duration = time_end - time_start
            overlaps.append(
                (
                    time_start + duration * (overlap_start - unit_start) / width,
                    time_start + duration * (overlap_end - unit_start) / width,
                )
            )
        if overlaps:
            return overlaps[0][0], overlaps[-1][1]
        return None

    timed = [overlap_time(span) for span in word_spans]
    result: list[KaraokeWord] = []
    index = 0
    total = len(words)
    while index < total:
        if timed[index] is not None:
            start, end = timed[index]  # type: ignore[misc]
            result.append(KaraokeWord(words[index], start, end))
            index += 1
            continue
        run_end = index
        while run_end < total and timed[run_end] is None:
            run_end += 1
        left = timed[index - 1][1] if index > 0 else cue_start  # type: ignore[index]
        right = timed[run_end][0] if run_end < total else cue_end  # type: ignore[index]
        weights = [max(1, len(words[k])) for k in range(index, run_end)]
        weight_sum = sum(weights)
        run_start = left
        for offset, weight in enumerate(weights):
            duration = (right - run_start) * weight / weight_sum
            result.append(KaraokeWord(words[index + offset], left, left + duration))
            left += duration
        index = run_end

    clamped: list[KaraokeWord] = []
    for word in result:
        start = max(cue_start, min(word.start, cue_end))
        end = max(start + 0.01, min(max(word.end, start), cue_end))
        clamped.append(KaraokeWord(word.text, start, end))
    return clamped


def _inline_color(primary: str, secondary: str) -> str:
    return (
        f"{{\\alpha&H00&\\1c{ass_color(primary)}&"
        f"\\2c{ass_color(secondary)}&}}"
    )


def _cs(seconds: float) -> int:
    """Convert seconds to centiseconds, never below one."""
    return max(1, int(round(max(0.0, seconds) * 100)))


def _k_tag(style: KaraokeStyle, centiseconds: int) -> str:
    """ASS karaoke syllable tag: smooth fill (\\kf) or hard fill (\\k)."""
    return ("\\kf" if style.smooth_fill else "\\k") + str(centiseconds)


def _paginate_cues(
    cues: Sequence[Cue], lines_per_slide: int, max_gap: float = 2.0
) -> list[list[Cue]]:
    """Split cues into non-overlapping pages of at most ``lines_per_slide``."""
    if lines_per_slide <= 0:
        return [list(cues)] if cues else []
    pages: list[list[Cue]] = []
    page: list[Cue] = []
    for cue in cues:
        if page:
            gap = cue.start - page[-1].end
            if len(page) >= lines_per_slide or gap > max_gap:
                pages.append(page)
                page = []
        page.append(cue)
    if page:
        pages.append(page)
    return pages


def _anchor_position(
    style: KaraokeStyle, play_res_x: int, play_res_y: int
) -> tuple[int, int]:
    """Return the ASS anchor point used by ``\\move`` for the chosen alignment."""
    if style.alignment in (1, 4, 7):
        x = style.margin_l
    elif style.alignment in (3, 6, 9):
        x = play_res_x - style.margin_r
    else:
        x = play_res_x // 2
    if style.alignment in (1, 2, 3):
        y = play_res_y - style.margin_v
    elif style.alignment in (7, 8, 9):
        y = style.margin_v
    else:
        y = play_res_y // 2
    return x, y


