@dataclass(frozen=True)
class KaraokeStyle:
    """Appearance of the karaoke subtitle: current line fills progressively."""

    font_name: str = "Arial"
    font_size: int = 60
    normal_color: str = "#FFFFFF"
    active_color: str = "#FFD54A"
    outline_color: str = "#000000"
    back_color: str = "#00000080"
    bold: bool = False
    outline: float = 3.0
    shadow: float = 1.0
    alignment: int = 2
    margin_l: int = 80
    margin_r: int = 80
    margin_v: int = 80
    lines_before: int = 1
    lines_after: int = 1
    lines_per_slide: int = 0
    transition: str = "none"
    transition_ms: int = 400
    entry_lead_ms: int = 200
    active_font_size: int = 0
    scroll_pause_seconds: float = 2.0
    stanza_boundaries: frozenset[int] = frozenset()
    smooth_fill: bool = True


@dataclass(frozen=True)
class KaraokeWord:
    text: str
    start: float
    end: float


